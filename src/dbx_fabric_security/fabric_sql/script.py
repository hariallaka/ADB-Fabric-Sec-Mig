"""Assembles the per-catalog T-SQL deployment script, the needs-review
script and the JSON report.

Each catalog's script is meant to be run against the SQL analytics
endpoint of that catalog's mirrored item, in order. Sections:

1. Schemas: target schemas for the views and the admin schema.
2. Roles and membership.
3. Views, in dependency order.
4. Admin views.
5. ``GRANT SELECT`` on views to roles. Nothing is ever granted on a
   mirrored base table.

``GO`` separates batches because ``CREATE VIEW`` must be the first
statement in a batch. sqlcmd, SSMS and VS Code mssql honour ``GO``. If a
runner doesn't, split on it. Every statement is idempotent (``IF NOT
EXISTS`` / ``CREATE OR ALTER``), so re-running is safe. Re-running does
**not** revoke grants or drop views that have since disappeared from
Databricks; see ``docs/fabric-sql-endpoint-views.md``.
"""

from __future__ import annotations

from dbx_fabric_security.extractor.models import ViewDefinition
from dbx_fabric_security.fabric_sql.admin_views import AdminExclusion, AdminView
from dbx_fabric_security.fabric_sql.grants import RolePlan
from dbx_fabric_security.fabric_sql.views import FabricViewScript, quote_ident, quote_nstring

_GO = "GO"


def _comment_block(lines: list[str], prefix: str = "-- ") -> str:
    out = []
    for line in lines:
        for sub in line.splitlines() or [""]:
            out.append(prefix + sub)
    return "\n".join(out)


def _catalog_script(
    catalog: str,
    scripts: list[FabricViewScript],
    admin_views: list[AdminView],
    plan: RolePlan,
    admin_schema: str,
) -> str:
    parts: list[str] = [
        _comment_block([
            "Generated by dbx-fabric-security generate-fabric-sql.",
            f"Run against: the SQL analytics endpoint of the Fabric mirrored item for Unity Catalog catalog '{catalog}'.",
            "Run top to bottom. GO separates batches. Every statement is idempotent.",
            "Users also need the mirrored item shared with them at Read (connect) only, with no",
            "ReadData/ReadAll and no workspace role, otherwise they can bypass these views.",
            "See docs/fabric-sql-endpoint-views.md.",
        ]),
    ]

    deployable = [s for s in scripts if s.deployable]
    schemas = sorted({s.target_schema for s in deployable} | ({admin_schema} if admin_views else set()))
    roles = sorted(r for r, by_cat in plan.role_grants.items() if catalog in by_cat)

    parts.append("\n-- ===== 1. Schemas =====")
    for schema in schemas:
        parts.append(
            f"IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = {quote_nstring(schema)})\n"
            f"    EXEC({quote_nstring('CREATE SCHEMA ' + quote_ident(schema))});\n{_GO}"
        )

    parts.append("\n-- ===== 2. Roles and membership =====")
    for role in roles:
        parts.append(
            f"IF NOT EXISTS (SELECT 1 FROM sys.database_principals WHERE name = {quote_nstring(role)} AND type = 'R')\n"
            f"    CREATE ROLE {quote_ident(role)};\n{_GO}"
        )
        for member in plan.role_members.get(role, []):
            parts.append(f"ALTER ROLE {quote_ident(role)} ADD MEMBER {quote_ident(member)};\n{_GO}")
        if not plan.role_members.get(role):
            parts.append(f"-- WARNING: role {quote_ident(role)} has no members in the role mapping CSV.")

    parts.append("\n-- ===== 3. Views (dependency order) =====")
    for s in deployable:
        header = [f"Source: {s.source_view}"] + [f"WARNING: {w}" for w in s.warnings]
        parts.append(f"{_comment_block(header)}\n{s.ddl}\n{_GO}")

    if admin_views:
        parts.append("\n-- ===== 4. Super business admin views (union of columns, OR of row filters) =====")
        for av in admin_views:
            header = [f"Base table: {av.base_table}", f"Combines: {', '.join(av.source_views)}"]
            header += [f"WARNING: {w}" for w in av.warnings]
            parts.append(f"{_comment_block(header)}\n{av.ddl}\n{_GO}")

    parts.append("\n-- ===== 5. Grants (views only, never base tables) =====")
    for role in roles:
        for target in plan.role_grants[role][catalog]:
            parts.append(f"GRANT SELECT ON {target} TO {quote_ident(role)};\n{_GO}")

    return "\n".join(parts) + "\n"


def _review_script(catalog: str, scripts: list[FabricViewScript], views_by_name: dict[str, ViewDefinition]) -> str:
    blocked = [s for s in scripts if not s.deployable]
    parts = [
        _comment_block([
            f"Views from catalog '{catalog}' that were NOT put in the deployment script.",
            "Nobody has been granted access to them in Fabric. Fix each one by hand, add it to",
            "the deployment script and add its GRANTs. Everything below is commented out on purpose.",
        ])
    ]
    for s in blocked:
        lines = [f"===== {s.source_view} =====", "Blocking issues:"]
        lines += [f"  - {i}" for i in s.blocking_issues]
        if s.warnings:
            lines += ["Warnings:"] + [f"  - {w}" for w in s.warnings]
        if s.grantees:
            lines.append(f"Databricks grantees (access withheld): {', '.join(s.grantees)}")
        lines += ["", "Original Databricks SQL:"]
        lines += views_by_name[s.source_view].raw_sql.splitlines()
        if s.ddl:
            lines += ["", "Best-effort T-SQL (unverified):"] + s.ddl.splitlines()
        parts.append("\n" + _comment_block(lines))
    return "\n".join(parts) + "\n"


def build_fabric_sql_outputs(
    views: list[ViewDefinition],
    scripts: list[FabricViewScript],
    admin_views: list[AdminView],
    admin_exclusions: list[AdminExclusion],
    plan: RolePlan,
    admin_schema: str,
    admin_role: str,
) -> tuple[dict[str, str], dict]:
    """Returns ``({relative_file_name: content}, report)``."""
    views_by_name = {v.fq_name: v for v in views}
    catalogs = sorted({s.catalog for s in scripts if s.catalog} | {a.catalog for a in admin_views})

    files: dict[str, str] = {}
    for catalog in catalogs:
        cat_scripts = [s for s in scripts if s.catalog == catalog]
        cat_admin = [a for a in admin_views if a.catalog == catalog]
        files[f"{catalog}__deploy.sql"] = _catalog_script(catalog, cat_scripts, cat_admin, plan, admin_schema)
        if any(not s.deployable for s in cat_scripts):
            files[f"{catalog}__needs_review.sql"] = _review_script(catalog, cat_scripts, views_by_name)
    uncataloged = [s for s in scripts if not s.catalog]
    if uncataloged:
        files["no_catalog__needs_review.sql"] = _review_script("(none)", uncataloged, views_by_name)

    report = {
        "summary": {
            "views": len(scripts),
            "deployableViews": sum(s.deployable for s in scripts),
            "needsReviewViews": sum(not s.deployable for s in scripts),
            "adminViews": len(admin_views),
            "adminExclusions": len(admin_exclusions),
            "roles": len(plan.role_grants),
            "unmappedGrantees": len(plan.unmapped_grantees),
            "overgrantWarnings": len(plan.overgrant_warnings),
            "adminRole": admin_role,
            "adminSchema": admin_schema,
        },
        "views": [s.as_dict() for s in scripts],
        "adminViews": [a.as_dict() for a in admin_views],
        "adminExclusions": [e.as_dict() for e in admin_exclusions],
        "rolePlan": plan.as_dict(),
    }
    return files, report
